const { chromium } = require('playwright');
const { jeton, fichierCle, dossier, preparer } = require('./aides.js');
const fs = require('fs');
const BASE = process.env.NEXORA_URL || 'http://127.0.0.1:8765/';
const APP = BASE + 'app/';
let echecs = 0;
const verif = (ok, texte) => { console.log(ok ? '  ✓' : '  ✗ ÉCHEC', texte); if (!ok) echecs++; };

(async () => {
  const b = await chromium.launch();
  const opts = { viewport: { width: 393, height: 851 }, isMobile: true, hasTouch: true, locale: 'fr-FR', acceptDownloads: true, serviceWorkers: 'block' };
  const csp = [];
  const nouvelle = async (ctx) => {
    const p = await ctx.newPage();
    p.on('pageerror', (e) => csp.push('pageerror: ' + e.message));
    p.on('dialog', async (d) => { csp.push('DIALOGUE INATTENDU: ' + d.message()); await d.dismiss(); });
    await p.addInitScript(() => document.addEventListener('securitypolicyviolation', (e) => console.error('CSP ' + e.violatedDirective + ' ' + e.blockedURI)));
    p.on('console', (m) => { if (m.type() === 'error') csp.push(m.text()); });
    return p;
  };
  const codeDe = async (p) => { await p.goto(APP); await p.waitForSelector('.device-code'); return (await p.textContent('.device-code')).replace('-', ''); };
  const activer = async (p, t) => { await p.goto(APP + '#activer=' + t); await p.waitForTimeout(700); };
  const erreurActivation = async (p) => (await p.$('.activation .err')) ? (await p.textContent('.activation .err')) : '';

  // Téléphone A (le client qui a payé) et téléphone B (un autre atelier)
  const ctxA = await preparer(await b.newContext(opts)); const A = await nouvelle(ctxA);
  const ctxB = await preparer(await b.newContext(opts)); const B = await nouvelle(ctxB);
  const codeA = await codeDe(A); const codeB = await codeDe(B);
  console.log(`Codes : A=${codeA}  B=${codeB}`);
  verif(codeA !== codeB && /^[2-9A-HJ-NP-Z]{8}$/.test(codeA), 'chaque téléphone a un code unique, sans 0/O/1/I');

  console.log('\n1. Licence');
  const tsCreation = Date.now();
  const lienA = jeton({ v: 2, id: 'NXM-A', n: 'Atelier A', a: codeA, d: '2026-11-05', ts: tsCreation, exp: '2027-11-05' });
  await activer(B, lienA);
  const eB = await erreurActivation(B);
  verif(eB.includes('autre téléphone') && eB.includes(codeB.slice(0, 4)), 'lien de A refusé sur B : « ' + eB.slice(0, 60) + '… »');
  await activer(B, jeton({ v: 1, id: 'OLD', n: 'Vieux', d: '2026-11-05' }));
  verif((await erreurActivation(B)).includes('ancienne version'), 'ancien format de lien (sans code téléphone) refusé');
  const [p1, s1] = lienA.split('.');
  const modifie = Buffer.from(JSON.stringify({ ...JSON.parse(Buffer.from(p1, 'base64url')), a: codeB })).toString('base64url') + '.' + s1;
  await activer(B, modifie);
  verif((await erreurActivation(B)).includes('pas valide'), 'lien de A modifié pour le code de B : signature refusée');
  await B.evaluate(async () => { const { db } = await import('./js/db.js'); await db.definir('licence', 'AAAA.BBBB'); });
  await B.goto(APP); await B.waitForTimeout(500);
  verif(!!(await B.$('.device-code')), 'fausse licence écrite directement dans la base : refusée au démarrage');
  await activer(A, lienA);
  verif(!!(await A.$('.sheet')), 'le bon lien active bien le téléphone A');
  await A.click('.sheet .btn.ghost');
  await A.evaluate(async () => { const { db } = await import('./js/db.js'); await db.definir('dernierJour', '2028-01-01'); });
  await A.goto(APP); await A.waitForTimeout(500);
  verif((await erreurActivation(A)).includes('expiré'), 'date du téléphone remise en arrière : la licence reste expirée');
  await A.evaluate(async () => { const { db } = await import('./js/db.js'); await db.definir('dernierJour', '2026-11-05'); });
  await A.goto(APP); await A.waitForSelector('.stats');

  console.log('\n2. Injection de code dans les champs (XSS)');
  await A.goto(APP + '#/reparation/nouvelle'); await A.waitForSelector('form .card');
  await A.fill('input[placeholder="Nom du client"]', '<img src=x onerror="alert(1)">Pirate');
  await A.fill('input[placeholder="07 00 00 00 00"]', '0700000000');
  await A.fill('input[placeholder^="Samsung, Tecno"]', '<script>alert(2)</script>');
  await A.fill('textarea[placeholder="Ce que dit le client"]', '"><svg onload=alert(3)>');
  await A.fill('input[placeholder^="Code PIN"]', '0000');
  await A.click('form button[type=submit]'); await A.waitForSelector('.sheet'); await A.click('.sheet .btn.ghost');
  await A.waitForTimeout(400);
  const imgs = await A.$$eval('#vue img[src="x"], #vue script, #vue svg[onload]', (x) => x.length);
  verif(imgs === 0 && (await A.textContent('#vue')).includes('<img src=x'), 'le texte malveillant s\'affiche comme du texte, rien ne s\'exécute');
  const repId = A.url().split('/').pop();

  console.log('\n3. Sauvegarde');
  await A.goto(APP + '#/plus'); await A.waitForSelector('.card');
  const dlClair = A.waitForEvent('download'); await A.click('button:has-text("Sauvegarder maintenant")');
  const fClair = (await dlClair); const cheminClair = dossier + '/svg-clair.json'; await fClair.saveAs(cheminClair);
  const clair = fs.readFileSync(cheminClair, 'utf8');
  verif(clair.includes('Pirate') && !clair.includes('"code":"0000"'), 'sauvegarde sans mot de passe : codes de déverrouillage exclus');
  verif(!clair.includes('"licence"') && !clair.includes('"appareil"'), 'la licence et le code du téléphone ne sont pas copiés dans la sauvegarde');
  await A.goto(APP + '#/plus'); await A.waitForSelector('.card');
  await A.fill('input[placeholder="Mot de passe (conseillé)"]', 'Sanpedro2026!');
  const dlChiffre = A.waitForEvent('download'); await A.click('button:has-text("Sauvegarder maintenant")');
  const cheminChiffre = dossier + '/svg-chiffre.json'; await (await dlChiffre).saveAs(cheminChiffre);
  const chiffre = fs.readFileSync(cheminChiffre, 'utf8');
  verif(!chiffre.includes('Pirate') && !chiffre.includes('0700000000') && chiffre.includes('AES-GCM'), 'sauvegarde protégée : noms et numéros illisibles (chiffrés AES-GCM)');
  await A.goto(APP + '#/plus'); await A.waitForSelector('.card');
  await A.setInputFiles('input[type=file]', cheminChiffre); await A.waitForSelector('.sheet input[type=password]');
  await A.fill('.sheet input[type=password]', 'mauvais'); await A.click('.sheet button[type=submit]'); await A.waitForTimeout(1500);
  verif((await A.textContent('#toasts')).includes('Mot de passe incorrect'), 'mauvais mot de passe : restauration refusée');
  await A.setInputFiles('input[type=file]', cheminChiffre); await A.waitForSelector('.sheet input[type=password]');
  await A.fill('.sheet input[type=password]', 'Sanpedro2026!'); await A.click('.sheet button[type=submit]');
  await A.waitForSelector('.sheet .btn.danger'); await A.click('.sheet .btn.danger'); await A.waitForTimeout(1000);
  verif((await A.$$eval('.item', (x) => x.length)) >= 1, 'bon mot de passe : données restaurées, licence conservée');
  // Sauvegarde piégée : photo pointant vers un site extérieur
  let fuite = false; await ctxA.route('https://evil.example/**', (r) => { fuite = true; r.abort(); });
  const piege = JSON.parse(clair); piege.donnees.photos = [{ id: 'p1', reparationId: repId, blob: 'https://evil.example/espion.png' }];
  fs.writeFileSync(dossier + '/svg-piege.json', JSON.stringify(piege));
  await A.goto(APP + '#/plus'); await A.waitForSelector('.card');
  await A.setInputFiles('input[type=file]', dossier + '/svg-piege.json'); await A.waitForSelector('.sheet .btn.danger');
  await A.click('.sheet .btn.danger'); await A.waitForTimeout(1000);
  verif(!fuite, 'sauvegarde piégée (lien extérieur) : aucune connexion vers l\'extérieur');

  console.log('\n4. Code d\'accès');
  await A.goto(APP + '#/plus'); await A.waitForSelector('.card');
  await A.click('button:has-text("Définir un code")');
  const pins = await A.$$('.sheet input.pin');
  await pins[0].fill('1234'); await pins[1].fill('1234'); await A.click('.sheet button[type=submit]');
  verif((await A.textContent('.sheet .err')).includes('trop facile'), 'code trop simple (1234) refusé');
  await pins[0].fill('482915'); await pins[1].fill('482915'); await A.click('.sheet button[type=submit]'); await A.waitForTimeout(1200);
  await A.goto(APP + '#/'); await A.reload(); await A.waitForSelector('input.pin');
  verif(!(await A.$('.stats')), 'au redémarrage : écran verrouillé, aucune donnée visible');
  for (let i = 0; i < 5; i++) { await A.fill('input.pin', '111111'); await A.click('.activation button[type=submit]'); await A.waitForTimeout(500); }
  verif((await A.textContent('.activation .err')).includes('patientez'), '5 codes faux : attente imposée');
  await A.fill('input.pin', '482915'); await A.click('.activation button[type=submit]'); await A.waitForTimeout(800);
  verif(!(await A.$('.stats')), 'pendant l\'attente, même le bon code est refusé');
  const verrou = await A.evaluate(async () => { const { db } = await import('./js/db.js'); return JSON.stringify(await db.reglage('verrou')); });
  verif(!verrou.includes('482915'), 'le code n\'est pas enregistré, seulement son empreinte');
  await activer(A, lienA); await A.waitForTimeout(300);
  verif(!!(await A.$('input.pin')), 'ancien lien d\'activation (créé avant le code) : ne retire PAS le code');
  await activer(A, jeton({ v: 2, id: 'NXM-A2', n: 'Atelier A', a: codeA, d: '2026-11-05', ts: Date.now() + 1000 }));
  await A.waitForSelector('.stats', { timeout: 4000 }).catch(() => {});
  verif(!!(await A.$('.stats')), 'nouveau lien envoyé par NEXORA : code oublié retiré, données conservées');

  console.log('\n5. Outil de licences (votre clé privée)');
  const ctxV = await b.newContext({ viewport: { width: 393, height: 851 }, locale: 'fr-FR' });
  const V = await nouvelle(ctxV);
  await V.goto(BASE + 'outils/licence.html');
  await V.setInputFiles('#fichier-cle', fichierCle); await V.waitForSelector('#form:not([hidden])');
  await V.fill('#mdp1', 'court'); await V.fill('#mdp2', 'court'); await V.click('#memoriser');
  verif((await V.textContent('#err-mem')).includes('8 caractères'), 'mot de passe trop court refusé');
  await V.fill('#mdp1', 'Cle-Nexora-2026'); await V.fill('#mdp2', 'Cle-Nexora-2026'); await V.click('#memoriser'); await V.waitForTimeout(800);
  const stockage = await V.evaluate(() => JSON.stringify(localStorage));
  const prive = JSON.parse(fs.readFileSync(fichierCle)).d;
  verif(!stockage.includes(prive) && !stockage.includes('"d"'), 'clé mémorisée : jamais en clair dans le navigateur (chiffrée)');
  await V.reload(); await V.waitForSelector('#etat-protegee:not([hidden])');
  await V.fill('#mdp-ouvrir', 'mauvais-mot'); await V.click('#ouvrir'); await V.waitForTimeout(1200);
  verif((await V.textContent('#err-ouvrir')).includes('incorrect') && (await V.$('#form[hidden]')), 'mauvais mot de passe : clé inutilisable');
  await V.fill('#mdp-ouvrir', 'Cle-Nexora-2026'); await V.click('#ouvrir'); await V.waitForSelector('#form:not([hidden])');
  await V.fill('#nom', 'Atelier B'); await V.fill('#code', 'ZZZ'); await V.click('#form button[type=submit]');
  verif((await V.textContent('#err-form')).includes('invalide'), 'code téléphone mal saisi : refusé');
  await V.fill('#code', codeB.toLowerCase()); await V.fill('#base', APP); await V.dispatchEvent('#base', 'change');
  await V.click('#form button[type=submit]'); await V.waitForSelector('#resultat:not([hidden])');
  const lienB = await V.inputValue('#lien');
  await B.goto(lienB); await B.waitForSelector('.sheet', { timeout: 4000 }).catch(() => {});
  verif(!!(await B.$('.sheet')), 'lien créé par l\'outil pour le code de B : B est activé');
  await A.goto(lienB); await A.waitForTimeout(700);
  const dejaActif = await A.evaluate(async () => { const { db } = await import('./js/db.js'); return (await db.reglage('licence')) || ''; });
  const msgA = (await A.textContent('#toasts')) || '';
  verif(!!(await A.$('.stats')), 'téléphone A déjà activé : il reste dans l\'application (message d\'erreur seulement)');
  verif(dejaActif !== lienB.split('activer=')[1] && msgA.includes('autre téléphone'), 'le lien de B ouvert sur A : refusé, la licence de A reste en place');

  console.log('\nViolations CSP / erreurs :', csp.filter((x) => !x.includes('Failed to load resource')).length ? csp : 'aucune');
  console.log(echecs ? `\n${echecs} ÉCHEC(S)` : '\nTOUS LES TESTS DE SÉCURITÉ PASSENT');
  await b.close();
})().catch((e) => { console.error('ERREUR DE TEST :', e); process.exit(1); });
